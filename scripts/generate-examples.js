'use strict';
// Regenerates examples/ from the planner engine so the committed exports always match the tool.
// Usage: node scripts/generate-examples.js
const fs = require('fs');
const path = require('path');
const load = require('../test/extract-engine');

const ROOT = path.join(__dirname, '..');
const e = load(path.join(ROOT, 'index.html'));

const SCENARIOS = [
  { dir: 'aws-three-tier', cloud: 'aws', addr: '10.0.0.0', pfx: 16, az: 3, futureAz: true, preset: 'Three tier (web, app, data)',
    about: 'AWS, 10.0.0.0/16, three Availability Zones plus a reserved fourth-zone slot, public /24, private /20 and database /24 per zone.' },
  { dir: 'aws-eks-cluster', cloud: 'aws', addr: '10.10.0.0', pfx: 16, az: 3, futureAz: false, preset: 'EKS cluster',
    about: 'AWS EKS, 10.10.0.0/16, three zones, /19 node-and-pod subnets (8,187 usable each, enough for ~270 m5.large nodes at 29 pods with the VPC CNI), /24 public, /26 database.' },
  { dir: 'aws-hub-firewall-tgw', cloud: 'aws', addr: '10.255.0.0', pfx: 20, az: 3, futureAz: false, preset: 'Hub (firewall + TGW)',
    about: 'AWS inspection hub, 10.255.0.0/20, three zones, /26 firewall and public subnets and /28 Transit Gateway attachment subnets.' },
  { dir: 'aws-by-hosts', cloud: 'aws', addr: '172.16.0.0', pfx: 16, az: 2, futureAz: true, growth: 50, preset: 'By hosts',
    about: 'AWS, sized by hosts: 50 web, 800 app and 20 database hosts per zone with 50% growth headroom, two zones plus a reserved third.' },
  { dir: 'azure-three-tier', cloud: 'azure', addr: '10.20.0.0', pfx: 16, az: 3, futureAz: false, preset: 'Three tier (web, app, data)',
    about: 'Azure, 10.20.0.0/16. Azure subnets span all zones, so each tier is one subnet; 5 addresses reserved per subnet.' },
  { dir: 'gcp-three-tier', cloud: 'gcp', addr: '10.30.0.0', pfx: 16, az: 3, futureAz: false, preset: 'Three tier (web, app, data)',
    about: 'Google Cloud, 10.30.0.0/16. Subnets are regional; 4 addresses reserved per subnet.' },
];

const files = { aws: { 'main.tf': 'tfAws', 'template.yaml': 'cfnAws' }, azure: { 'azure.sh': 'azureCli' }, gcp: { 'gcloud.sh': 'gcloud' } };
const common = { 'subnets.csv': 'csv', 'subnets.json': 'json', 'subnets.md': 'md' };

for (const sc of SCENARIOS) {
  e.configure({ cloud: sc.cloud, addr: sc.addr, pfx: sc.pfx, az: sc.az, futureAz: !!sc.futureAz, contig: true, growth: sc.growth ?? 50, existing: '', routing: true, preset: sc.preset });
  const R = e.run();
  if (R.errors.length) throw new Error(sc.dir + ': ' + R.errors.join('; '));
  const dir = path.join(ROOT, 'examples', sc.dir);
  fs.mkdirSync(dir, { recursive: true });
  for (const [name, fn] of Object.entries({ ...(files[sc.cloud] || {}), ...common })) fs.writeFileSync(path.join(dir, name), e[fn](R) + '\n');
  const review = R.review.items.map(i => `- **${i.k.toUpperCase()}** ${i.t}`).join('\n');
  const hash = Buffer.from(JSON.stringify({ c: e.S.cloud, a: e.S.addr, p: e.S.pfx, z: e.S.az, f: e.S.futureAz ? 1 : 0, k: 1, g: e.S.growth, e: '', t: e.S.tiers.map(t => [t.n, t.r, t.m, t.v]), r: 1 })).toString('base64').replace(/=+$/, '');
  fs.writeFileSync(path.join(dir, 'README.md'), `# ${sc.dir}

${sc.about}

Open this exact plan in the tool: https://jhooq.com/tools/vpc-subnet-planner/#${hash}

## Plan

${e.md(R)}

Design review score: **${R.review.score}/100**

${review}

Files in this folder are generated by \`node scripts/generate-examples.js\` - do not edit them by hand.
`);
  console.log(`${sc.dir}: ${R.subnets.length} subnets, score ${R.review.score}, ${R.free.length} free blocks`);
}
